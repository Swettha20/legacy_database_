"""Privileged setup only. API credentials cannot provision databases or Oracle users."""
import os
import re
import psycopg2
from psycopg2 import sql


def provision():
    from .store import store
    conn = psycopg2.connect(host=os.getenv("PG_HOST", "postgres"), user=os.getenv("PG_USER", "postgres"),
                            password=os.environ["PG_PASSWORD"], dbname="postgres")
    conn.autocommit = True
    try:
        with conn.cursor() as cur:
            cur.execute("SELECT 1 FROM pg_roles WHERE rolname='moderniser'")
            if not cur.fetchone():
                cur.execute(sql.SQL("CREATE ROLE moderniser LOGIN PASSWORD {}").format(sql.Literal(os.environ["META_PASSWORD"])))
            cur.execute("SELECT 1 FROM pg_database WHERE datname='moderniser_meta'")
            if not cur.fetchone():
                cur.execute("CREATE DATABASE moderniser_meta OWNER moderniser")
    finally:
        conn.close()
    store.initialize()
    store.create_user("admin", os.environ["ADMIN_PASSWORD"], "admin", if_missing=True)


def grant_reader():
    import oracledb
    from config import ORACLE_DSN, ORACLE_PASSWORD
    password = os.environ["ORACLE_READER_PASSWORD"]
    if not re.fullmatch("[a-f0-9]{24}", password):
        raise ValueError("Reader password must be generated by start_all")
    with oracledb.connect(user="sys", password=ORACLE_PASSWORD, dsn=ORACLE_DSN, mode=oracledb.AUTH_MODE_SYSDBA) as conn:
        with conn.cursor() as cur:
            cur.execute("SELECT 1 FROM all_users WHERE username='MIG_READER'")
            if not cur.fetchone():
                cur.execute('CREATE USER MIG_READER IDENTIFIED BY "' + password + '"')
            cur.execute("GRANT CREATE SESSION TO MIG_READER")
            cur.execute("GRANT EXECUTE ON SYS.DBMS_FLASHBACK TO MIG_READER")
            cur.execute("""SELECT owner,table_name FROM all_tables
                           WHERE owner IN ('DEMO','SH') AND table_name NOT LIKE 'BIN$%'""")
            tables = cur.fetchall()
            for owner, table in tables:
                cur.execute(f'GRANT SELECT, FLASHBACK ON "{owner}"."{table}" TO MIG_READER')
