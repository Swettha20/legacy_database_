SET DEFINE OFF

CREATE TABLE departments (
        id         NUMBER(5)     PRIMARY KEY,
        name       VARCHAR2(80)  NOT NULL UNIQUE,
        parent_id  NUMBER(5)     REFERENCES departments(id)
    );

CREATE TABLE doctors (
        id             NUMBER(6)      PRIMARY KEY,
        full_name      VARCHAR2(120)  NOT NULL,
        department_id  NUMBER(5)      NOT NULL REFERENCES departments(id),
        license_no     VARCHAR2(20)   NOT NULL UNIQUE,
        hired          DATE           DEFAULT SYSDATE NOT NULL
    );

CREATE TABLE patients (
        id          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        full_name   VARCHAR2(120) NOT NULL,
        birth_date  DATE,
        phone       VARCHAR2(30),
        notes       CLOB
    );

CREATE TABLE medicines (
        sku         VARCHAR2(12)   PRIMARY KEY,
        name        VARCHAR2(100)  NOT NULL,
        unit_price  NUMBER(8,2)    NOT NULL CHECK (unit_price >= 0),
        stock       NUMBER(6)      DEFAULT 0 NOT NULL CHECK (stock >= 0)
    );

CREATE TABLE appointments (
        id          NUMBER(9)     PRIMARY KEY,
        patient_id  NUMBER        NOT NULL REFERENCES patients(id) ON DELETE CASCADE,
        doctor_id   NUMBER(6)     NOT NULL REFERENCES doctors(id),
        starts_at   DATE          NOT NULL,
        status      VARCHAR2(12)  DEFAULT 'BOOKED' NOT NULL CHECK (status IN ('BOOKED', 'DONE', 'CANCELLED')),
        fee         NUMBER(8,2),
        booked_at   TIMESTAMP(6)  DEFAULT SYSTIMESTAMP NOT NULL,
        CONSTRAINT uq_doctor_slot UNIQUE (doctor_id, starts_at)
    );

CREATE TABLE prescriptions (
        appointment_id  NUMBER(9)     NOT NULL REFERENCES appointments(id) ON DELETE CASCADE,
        medicine_sku    VARCHAR2(12)  NOT NULL REFERENCES medicines(sku),
        quantity        NUMBER(4)     NOT NULL CHECK (quantity > 0),
        PRIMARY KEY (appointment_id, medicine_sku)
    );

