PROCEDURES_SQL = """
CREATE OR REPLACE FUNCTION doctor_load(p_doctor_id IN NUMBER) RETURN NUMBER AS
    v_count NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_count FROM appointments
    WHERE doctor_id = p_doctor_id AND status = 'BOOKED';
    RETURN v_count;
END doctor_load;
/

CREATE OR REPLACE FUNCTION appointment_total(p_appointment_id IN NUMBER) RETURN NUMBER AS
    v_total NUMBER := 0;
BEGIN
    FOR rx IN (SELECT m.unit_price, p.quantity
               FROM prescriptions p JOIN medicines m ON m.sku = p.medicine_sku
               WHERE p.appointment_id = p_appointment_id) LOOP
        v_total := v_total + rx.unit_price * rx.quantity;
    END LOOP;
    RETURN v_total;
END appointment_total;
/

CREATE OR REPLACE PROCEDURE book_appointment(p_patient_id IN NUMBER, p_doctor_id IN NUMBER,
                                             p_when IN DATE, p_id OUT NUMBER) AS
    v_busy NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_busy FROM appointments
    WHERE doctor_id = p_doctor_id AND starts_at = p_when AND status <> 'CANCELLED';
    IF v_busy > 0 THEN
        RAISE_APPLICATION_ERROR(-20101, 'Doctor ' || p_doctor_id || ' is already booked at that time');
    END IF;
    SELECT NVL(MAX(id), 0) + 1 INTO p_id FROM appointments;
    INSERT INTO appointments (id, patient_id, doctor_id, starts_at)
    VALUES (p_id, p_patient_id, p_doctor_id, p_when);
END book_appointment;
/

CREATE OR REPLACE PROCEDURE cancel_appointment(p_id IN NUMBER) AS
BEGIN
    UPDATE appointments SET status = 'CANCELLED' WHERE id = p_id AND status = 'BOOKED';
    IF SQL%ROWCOUNT = 0 THEN
        RAISE_APPLICATION_ERROR(-20102, 'Appointment ' || p_id || ' cannot be cancelled');
    END IF;
    FOR rx IN (SELECT medicine_sku, quantity FROM prescriptions WHERE appointment_id = p_id) LOOP
        UPDATE medicines SET stock = stock + rx.quantity WHERE sku = rx.medicine_sku;
    END LOOP;
END cancel_appointment;
/
"""


def _literal(value) -> str:
    """One Python value as an Oracle SQL literal."""
    if value is None:
        return "NULL"
    if isinstance(value, datetime.datetime):
        return f"TO_DATE('{value:%Y-%m-%d %H:%M:%S}', 'YYYY-MM-DD HH24:MI:SS')"
    if isinstance(value, (int, Decimal)):
        return str(value)
    return "'" + str(value).replace("'", "''") + "'"


def as_script() -> str:
    """The whole sample as ONE plain Oracle SQL script (what you would upload on the web page)."""
    out = ["-- Medical clinic sample: tables, data and stored procedures, as one Oracle script.",
           "-- Upload it on the web page (\"An Oracle SQL file I upload\").", "SET DEFINE OFF", ""]
    for ddl in TABLES_DDL:
        out.append(ddl + ";\n")
    for table, insert, rows in DATA:
        columns = insert[insert.index("(") + 1:insert.index(")")]
        for row in rows:
            out.append(f"INSERT INTO {table} ({columns}) VALUES ({', '.join(_literal(v) for v in row)});")
        out.append("")
    out.append("COMMIT;\n")
    out.append(PROCEDURES_SQL.strip() + "\n")
    return "\n".join(out)


